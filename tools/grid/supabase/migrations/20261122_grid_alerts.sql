-- Grid background alerts: the two tables, the sweep token, and the five-minute schedule.
-- Applied to the City project (gpkjvihkyectnenvnbng) on 2026-11-22 as migrations
-- `grid_alerts_tables` and `grid_alerts_sweep_schedule`. Kept here so the service can be rebuilt.

-- Both tables are closed to the public API: row level security on, no policies, no grants to anon or
-- authenticated. Only the service role (the edge function) reads them.
create table if not exists public.grid_push_subs (
  id text primary key,                          -- SHA-256 (hex) of the push endpoint
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  places jsonb not null default '[]'::jsonb,    -- [{fips, label}], at most five counties
  min_out integer not null default 10 check (min_out between 1 and 1000000),
  weather boolean not null default true,
  restore boolean not null default true,
  state jsonb not null default '{}'::jsonb,     -- what has already been sent, so nothing repeats
  fails integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_push_at timestamptz,
  last_test_at timestamptz
);
comment on table public.grid_push_subs is 'Grid alerts: one row per device. Push endpoint and keys, counties, threshold, two choices, dedupe state. No name, email, IP, precise location or health data.';
alter table public.grid_push_subs enable row level security;
revoke all on public.grid_push_subs from anon, authenticated;

create table if not exists public.grid_alert_config (
  id integer primary key default 1 check (id = 1),
  vapid_public text,
  vapid_private_jwk jsonb,                      -- generated by the function on first use; never leaves the server
  sweep_token text not null,
  last_sweep jsonb,
  created_at timestamptz not null default now()
);
comment on table public.grid_alert_config is 'Grid alerts: the Web Push (VAPID) key pair, the sweep token, and the last sweep summary.';
alter table public.grid_alert_config enable row level security;
revoke all on public.grid_alert_config from anon, authenticated;

-- One random sweep token, written to the config row (read by the function) and to Vault (read by pg_cron).
do $$
declare t text := encode(extensions.gen_random_bytes(32), 'hex');
begin
  if not exists (select 1 from public.grid_alert_config where id = 1) then
    insert into public.grid_alert_config (id, sweep_token) values (1, t);
    perform vault.create_secret(t, 'grid_alerts_sweep_token', 'Grid alerts: token pg_cron sends to grid-alerts?op=sweep');
  end if;
end $$;


"""Emit certificate.json as a Coq data module (untrusted witnesses; the checker is in
E47KernelCertificate.v). Deterministic: same JSON -> byte-identical .v file."""
import json, hashlib, os
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, "certificate.json")))
def zlit(v): return f"({v})" if v < 0 else str(v)
def mat(B): return "[" + ";\n   ".join("[" + ";".join(zlit(v) for v in row) + "]" for row in B) + "]"
def nats(l): return "[" + ";".join(str(v) for v in l) + "]%nat"
out = []
out.append("""(* E47KernelCertificateData.v -- GENERATED by gen/emit_coq_data.py from
   gen/certificate.json (sha256 %s).
   Untrusted witness data only: every fact used about these numbers is re-checked by
   vm_compute in E47KernelCertificate.v. Coq standard library only. *)
From Coq Require Import List ZArith.
Import ListNotations.
Open Scope Z_scope.

Module KernelCertificateData.
""" % hashlib.sha256(open(os.path.join(HERE, "certificate.json"),"rb").read()).hexdigest())
for l in d["levels"]:
    i = l["level"]
    out.append(f"(* level {i}: Casimir {l['casimir']}, dimension {l['dim']} *)")
    out.append(f"Definition beta{i} : Z := {l['beta']}.")
    out.append(f"Definition piv{i} : list nat := {nats(l['pivots'])}.")
    out.append(f"Definition B{i} : list (list Z) :=\n  {mat(l['B'])}.\n")
k = d["kernel"]
out.append(f"(* ker K = ker (C-6)(C-30): dimension {k['dim']} *)")
out.append(f"Definition betaK : Z := {k['beta']}.")
out.append(f"Definition pivK : list nat := {nats(k['pivots'])}.")
out.append(f"Definition BK : list (list Z) :=\n  {mat(k['B'])}.\n")
out.append("End KernelCertificateData.\n")
open(os.path.join(HERE, "..", "E47KernelCertificateData.v"), "w").write("\n".join(out))
print("written", sum(len(s) for s in out), "chars")
